// Automatically sync a dedicated downloadable APK in the project root after every successful build.
abstract class SyncRootApkTask : DefaultTask() {
  @get:InputFiles
  @get:PathSensitive(PathSensitivity.NONE)
  abstract val apkFiles: ConfigurableFileCollection

  @get:OutputFile
  abstract val destApk: RegularFileProperty

  @TaskAction
  fun sync() {
    val src = apkFiles.files.asSequence()
      .flatMap { if (it.isDirectory) it.walkTopDown() else sequenceOf(it) }
      .firstOrNull { it.isFile && it.extension == "apk" }
    if (src != null) {
      src.copyTo(destApk.get().asFile, overwrite = true)
    }
  }
}

val syncDebugRootApk = tasks.register<SyncRootApkTask>("syncDebugRootApk") {
  apkFiles.from(layout.buildDirectory.dir("outputs/apk/debug"))
  destApk.set(rootProject.layout.projectDirectory.file("WA-Auto-Scheduler.apk"))
  mustRunAfter("packageDebug", "createDebugApkListingFileRedirect")
}

val syncReleaseRootApk = tasks.register<SyncRootApkTask>("syncReleaseRootApk") {
  apkFiles.from(layout.buildDirectory.dir("outputs/apk/release"))
  destApk.set(rootProject.layout.projectDirectory.file("WA-Auto-Scheduler.apk"))
  mustRunAfter("packageRelease", "createReleaseApkListingFileRedirect")
}

tasks.configureEach {
  if (name == "assembleDebug") finalizedBy(syncDebugRootApk)
  if (name == "assembleRelease") finalizedBy(syncReleaseRootApk)
}
